  anexos: [
    for (final a in (j['anexos'] as List?) ?? const [])
      Anexo(
        tipo: lerEnum(AnexoTipo.values, a['tipo'], AnexoTipo.link),
        titulo: lerTexto(a['titulo']),
        url: lerTexto(a['url']),
      ),
  ],
